// tree -- ASCII parent/child process tree -------------------------------
//
// Walks EnumProcesses(), builds parent->children map, renders depth-first
// with box-drawing characters. Roots are PIDs whose ParentPid isn't itself
// in the list (System, services orphaned by their original parent, etc).

static void PrintTreeNode(uint32_t pid,
                          const std::unordered_map<uint32_t, const ProcessInfo*>& byPid,
                          const std::unordered_map<uint32_t, std::vector<uint32_t>>& kids,
                          const std::wstring& prefix, bool last) {
    auto pit = byPid.find(pid);
    const ProcessInfo* p = pit != byPid.end() ? pit->second : nullptr;
    const wchar_t* name = p ? p->imageName.c_str() : L"(gone)";
    wprintf(L"%s%s %u %s\n",
            prefix.c_str(),
            last ? L"└─" : L"├─",   // └─ or ├─
            pid, name);

    auto kit = kids.find(pid);
    if (kit == kids.end()) return;
    std::wstring childPrefix = prefix + (last ? L"   " : L"│  ");  // "│  "
    const auto& v = kit->second;
    for (size_t i = 0; i < v.size(); ++i) {
        PrintTreeNode(v[i], byPid, kids, childPrefix, i + 1 == v.size());
    }
}

// Unified process row so the tree builder doesn't care whether the rows
// came from the kernel (DriverSession::enumPids) or user-mode
// (NtQuerySystemInformation via EnumProcesses).
struct TreeRow {
    uint32_t pid       = 0;
    uint32_t parentPid = 0;
    std::wstring name;
};

// Real-time process monitor — subscribes via the driver's
// PsSetCreateProcessNotifyRoutineEx-backed stream and prints every
// create/exit as it happens. Ctrl+C stops the loop (the kernel read
// has a 2s timeout so cancellation is bounded).
int CmdProcMonitor(int argc, wchar_t** argv) {
    wclap::App app(L"winternal proc monitor");
    app.about(L"Live process create/exit stream — driver-side notify routine "
              L"(PsSetCreateProcessNotifyRoutineEx) feeds an in-kernel ring; "
              L"this CLI blocks in IOCTL_PROC_MONITOR_READ for events.")
       .arg(wclap::Arg(L"include").long_name(L"include").takes_value()
                .help(L"Wildcard against image path (* spans \\); only matches print"))
       .arg(wclap::Arg(L"exclude").long_name(L"exclude").takes_value()
                .help(L"Wildcard against image path; matches are dropped"))
       .arg(wclap::Arg(L"cmd").long_name(L"cmd").help(L"Also print command line"))
       .arg(wclap::Arg(L"nocolor").long_name(L"nocolor").help(L"Disable ANSI color"));
    auto m = app.parse(argc, argv);
    auto includePat = m.value(L"include");
    auto excludePat = m.value(L"exclude");
    bool showCmd   = m.present(L"cmd");
    if (m.present(L"nocolor")) wclap::style::force(false);
    else                       wclap::style::init();

    DriverSession s;
    if (!OpenDriverOrHint(s)) return 1;
    if (!s.procMonitorStart()) {
        fwprintf(stderr, L"proc monitor: start failed (%lu)\n", ::GetLastError());
        return 1;
    }

    // Shell-style wildcard, same semantics as the NTFS filter rules:
    // `*` spans path separators, `?` one char, case-insensitive.
    auto match = [](const std::wstring& pat, const std::wstring& s) {
        size_t pi = 0, si = 0, starPi = (size_t)-1, starSi = 0;
        while (si < s.size()) {
            if (pi < pat.size() && pat[pi] == L'*') { starPi = pi++; starSi = si; continue; }
            if (pi < pat.size()) {
                wchar_t p = pat[pi], c = s[si];
                if (p >= L'A' && p <= L'Z') p += 32;
                if (c >= L'A' && c <= L'Z') c += 32;
                if (p == L'?' || p == c) { ++pi; ++si; continue; }
            }
            if (starPi != (size_t)-1) { pi = starPi + 1; si = ++starSi; continue; }
            return false;
        }
        while (pi < pat.size() && pat[pi] == L'*') ++pi;
        return pi == pat.size();
    };

    wprintf(L"%ls-- monitoring processes (Ctrl+C to stop) --%ls\n",
            wclap::style::DIM(), wclap::style::RESET());
    wprintf(L"%ls%-12ls  %-7ls  %-7ls  %-8ls  %ls%ls\n",
            wclap::style::BOLD(), L"TIME", L"PID", L"PPID/BY", L"EVENT", L"IMAGE",
            wclap::style::RESET());

    while (!Aborted()) {
        auto events = s.procMonitorRead();
        for (auto& e : events) {
            if (includePat && !match(*includePat, e.image)) continue;
            if (excludePat && match(*excludePat, e.image))  continue;

            FILETIME ft{ (DWORD)e.timestampNs, (DWORD)(e.timestampNs >> 32) };
            SYSTEMTIME u{}, lt{};
            ::FileTimeToSystemTime(&ft, &u);
            ::SystemTimeToTzSpecificLocalTime(nullptr, &u, &lt);

            const wchar_t* color;
            const wchar_t* tag;
            switch (e.eventType) {
            case 0: color = wclap::style::enabled() ? L"\x1b[1;32m" : L""; tag = L"CREATE";   break;
            case 1: color = wclap::style::enabled() ? L"\x1b[1;31m" : L""; tag = L"EXIT";     break;
            case 2: color = wclap::style::enabled() ? L"\x1b[1;33m" : L""; tag = L"TERM-REQ"; break;
            default: color = L""; tag = L"?";                                                  break;
            }

            if (e.dropped) {
                wprintf(L"%ls(%u events dropped — ring overflow)%ls\n",
                        wclap::style::DIM(), e.dropped, wclap::style::RESET());
            }
            // TERMINATE_REQ uses the second column for the CALLER (creatingPid).
            // Re-purposing PPID slot here makes the "who→whom" relationship
            // visible without widening the table.
            uint32_t col2 = (e.eventType == 2) ? e.creatingPid : e.parentPid;
            wprintf(L"%02u:%02u:%02u.%03u  %-7u  %-7u  %ls%-8ls%ls  %ls\n",
                    lt.wHour, lt.wMinute, lt.wSecond, lt.wMilliseconds,
                    e.pid, col2,
                    color, tag, wclap::style::RESET(),
                    e.image.empty() ? L"-" : e.image.c_str());
            if (showCmd && !e.cmdLine.empty()) {
                wprintf(L"%ls                                              cmd:%ls %ls\n",
                        wclap::style::DIM(), wclap::style::RESET(), e.cmdLine.c_str());
            }
        }
    }

    s.procMonitorStop();
    wprintf(L"%ls-- stopped --%ls\n", wclap::style::DIM(), wclap::style::RESET());
    return 0;
}

static const wchar_t* ProcActionName(uint32_t a) {
    switch (a) {
    case 0: return L"ALLOW";
    case 1: return L"DENY";
    case 2: return L"LOG";
    default: return L"?";
    }
}

static int ParseProcAction(std::wstring_view s) {
    auto eq = [&](const wchar_t* lit) {
        if (wcslen(lit) != s.size()) return false;
        for (size_t i = 0; i < s.size(); ++i) {
            wchar_t a = s[i]; if (a >= L'A' && a <= L'Z') a += 32;
            if (a != lit[i]) return false;
        }
        return true;
    };
    if (eq(L"allow")) return 0;
    if (eq(L"deny"))  return 1;
    if (eq(L"log"))   return 2;
    return -1;
}

// Name-based status lookup — accepts SDK macro spelling directly, so
// callers can write `--status ERROR_BAD_LENGTH` or `--status STATUS_INVALID_HANDLE`
// without remembering the numeric value. There is no Win32 API for
// runtime name->value lookup (these are preprocessor macros — never
// reified at runtime), so the table is generated at build time from the
// SDK headers by tools/generate-status-db.ps1 (see StatusDb.gen.h).
//
// For ERROR_* inputs we need the kernel's canonical NTSTATUS (e.g.
// ERROR_ACCESS_DENIED -> STATUS_ACCESS_DENIED 0xC0000022), not the
// FACILITY_WIN32-encoded HRESULT_FROM_WIN32 form (0x80070005). The
// canonical mapping lives inside ntdll's RtlpDosErrorToNtStatusMap and
// isn't exposed directly — but RtlNtStatusToDosError goes the other
// way, so we run every known STATUS through it once and stash the
// first STATUS we see for each Win32 code. That gives the same result
// the kernel itself uses when translating in either direction.

// RtlNtStatusToDosError is declared by <winternl.h>.

static const std::unordered_map<uint32_t, uint32_t>& Win32ToCanonicalNtStatus() {
    static const auto map = []{
        std::unordered_map<uint32_t, uint32_t> r;
        r.reserve(winternal_status_db::kNtStatusNamesCount);
        for (size_t i = 0; i < winternal_status_db::kNtStatusNamesCount; ++i) {
            uint32_t status = winternal_status_db::kNtStatusNames[i].value;
            ULONG    code   = RtlNtStatusToDosError((LONG)status);
            // RtlNtStatusToDosError falls back to ERROR_MR_MID_NOT_FOUND
            // for unmappable statuses; skip those so we don't poison the
            // common Win32 codes with arbitrary obscure NTSTATUSes.
            if (code == 0 || code == 317 /* ERROR_MR_MID_NOT_FOUND */) continue;
            // First STATUS seen for a given Win32 code wins. The
            // generator emits names in alphabetical order, but that's
            // good enough — for any "duplicate" Win32 code, all mapping
            // STATUSes are semantically interchangeable from kernel POV.
            if (r.find(code) == r.end()) r[code] = status;
        }
        return r;
    }();
    return map;
}

static bool LookupNtStatusByName(const std::wstring& s, uint32_t& out) {
    for (size_t i = 0; i < winternal_status_db::kNtStatusNamesCount; ++i) {
        if (_wcsicmp(s.c_str(), winternal_status_db::kNtStatusNames[i].name) == 0) {
            out = winternal_status_db::kNtStatusNames[i].value;
            return true;
        }
    }
    return false;
}

static bool LookupWin32ByName(const std::wstring& s, uint32_t& outWin32) {
    for (size_t i = 0; i < winternal_status_db::kWin32ErrorNamesCount; ++i) {
        if (_wcsicmp(s.c_str(), winternal_status_db::kWin32ErrorNames[i].name) == 0) {
            outWin32 = winternal_status_db::kWin32ErrorNames[i].value;
            return true;
        }
    }
    return false;
}

static bool MatchStatusName(const std::wstring& s, uint32_t& out) {
    if (s.size() >= 7 && _wcsnicmp(s.c_str(), L"STATUS_", 7) == 0) {
        return LookupNtStatusByName(s, out);
    }
    if (s.size() >= 6 && _wcsnicmp(s.c_str(), L"ERROR_", 6) == 0) {
        uint32_t win32code = 0;
        if (!LookupWin32ByName(s, win32code)) return false;
        const auto& m = Win32ToCanonicalNtStatus();
        auto it = m.find(win32code);
        if (it != m.end()) { out = it->second; return true; }
        // Win32 code with no kernel-canonical NTSTATUS mapping: fall back
        // to the FACILITY_WIN32-encoded form, which the kernel does accept.
        out = (uint32_t)(0x80070000u | (win32code & 0xFFFFu));
        return true;
    }
    return false;
}

// --status accepts four flavors:
//   - ERROR_* or STATUS_*  SDK macro name (case-insensitive)
//   - 0xNNNNNNNN  full NTSTATUS hex (used verbatim, including SUCCESS for `protect`)
//   - NNNNNNNN    bare hex — auto-detected when the string contains a-f/A-F
//                 OR is exactly 8 characters of [0-9a-fA-F]
//   - decimal     small Win32 error code, mapped to the corresponding NTSTATUS:
//       0   STATUS_SUCCESS              "deny by lying" (only useful for protect;
//                                        proc rule coerces to ACCESS_DENIED, see below)
//       1   STATUS_OBJECT_NAME_NOT_FOUND
//       2   STATUS_OBJECT_NAME_NOT_FOUND  (ERROR_FILE_NOT_FOUND)
//       3   STATUS_OBJECT_PATH_NOT_FOUND
//       5   STATUS_ACCESS_DENIED        the obvious default
//       6   STATUS_INVALID_HANDLE
//       8   STATUS_NO_MEMORY
//      32   STATUS_SHARING_VIOLATION
//      87   STATUS_INVALID_PARAMETER
//     267   STATUS_NOT_A_DIRECTORY
// Anything not recognized falls through verbatim.
//
// IMPORTANT: NT_SUCCESS values supplied to a proc-rule DENY are coerced by
// the kernel to STATUS_ACCESS_DENIED — the CreateProcess notify path uses
// CreationStatus as both the syscall return AND the veto signal, so we
// can't actually deny while returning success there. `proc protect` is
// different (the detour controls both return and "do the original call")
// so SUCCESS works as a fooling trick there.
static uint32_t ResolveStatusInput(const std::wstring& s) {
    if (s.empty()) return 0xC0000022u;
    auto starts = [&](const wchar_t* p){ return s.rfind(p, 0) == 0; };

    // SDK macro names first — ERROR_* and STATUS_* (case-insensitive). Lets
    // callers write `--status ERROR_BAD_LENGTH` or `--status STATUS_INVALID_HANDLE`
    // verbatim instead of remembering the numeric code.
    if ((s.size() >= 6 && (_wcsnicmp(s.c_str(), L"ERROR_",  6) == 0)) ||
        (s.size() >= 7 && (_wcsnicmp(s.c_str(), L"STATUS_", 7) == 0))) {
        uint32_t resolved = 0;
        if (MatchStatusName(s, resolved)) return resolved;
        // Unknown but well-formed name: fall through to hex/decimal parsing
        // (it'll likely return 0 or junk; better to let the user see that
        // than silently default to ACCESS_DENIED).
    }

    // Explicit 0x / 0X prefix → hex
    if (starts(L"0x") || starts(L"0X")) {
        return (uint32_t)wcstoul(s.c_str(), nullptr, 16);
    }
    // Bare hex: any a-f/A-F means it can't be decimal. Also accept the
    // 8-char [0-9a-f] form (typical NTSTATUS shape like C0000022).
    bool hasHex = false;
    bool allHex = !s.empty();
    for (wchar_t c : s) {
        if ((c >= L'a' && c <= L'f') || (c >= L'A' && c <= L'F')) hasHex = true;
        else if (!(c >= L'0' && c <= L'9')) { allHex = false; break; }
    }
    if (hasHex && allHex) {
        return (uint32_t)wcstoul(s.c_str(), nullptr, 16);
    }
    if (allHex && s.size() == 8) {
        return (uint32_t)wcstoul(s.c_str(), nullptr, 16);
    }

    // Decimal Win32 code → mapped NTSTATUS
    uint32_t v = (uint32_t)wcstoul(s.c_str(), nullptr, 10);
    switch (v) {
        case 0:   return 0x00000000u;
        case 1:   return 0xC0000034u;
        case 2:   return 0xC0000034u;
        case 3:   return 0xC000003Au;
        case 5:   return 0xC0000022u;
        case 6:   return 0xC0000008u;
        case 8:   return 0xC0000017u;
        case 32:  return 0xC0000043u;
        case 87:  return 0xC000000Du;
        case 267: return 0xC0000103u;
        default:  return v;
    }
}

static const wchar_t* WellKnownStatusName(uint32_t ntstatus) {
    switch (ntstatus) {
        case 0x00000000u: return L"SUCCESS";
        case 0xC0000022u: return L"ACCESS_DENIED";
        case 0xC0000034u: return L"NAME_NOT_FOUND";
        case 0xC000003Au: return L"PATH_NOT_FOUND";
        case 0xC0000008u: return L"INVALID_HANDLE";
        case 0xC0000017u: return L"NO_MEMORY";
        case 0xC0000043u: return L"SHARING_VIOL";
        case 0xC000000Du: return L"INVALID_PARAM";
        case 0xC0000103u: return L"NOT_A_DIR";
        case 0xC0000120u: return L"CANCELLED";
        case 0xC0000005u: return L"ACCESS_VIOL";
        default:          return L"";
    }
}

static int CmdProcRuleAdd(int argc, wchar_t** argv) {
    wclap::App app(L"winternal proc rule add");
    app.about(L"Install a process-create rule. Patterns use path-aware shell "
              L"wildcards: `*` spans any chars including `\\`, `?` matches one. "
              L"They match the kernel image path the FSD sees on create — typically "
              L"`\\??\\C:\\Windows\\System32\\foo.exe`. Examples:\n"
              L"  *\\powershell.exe        -- block all PowerShell launches\n"
              L"  *\\Temp\\*.exe           -- block any .exe inside any \\Temp\\\n"
              L"  *malware*               -- block paths containing 'malware'\n"
              L"\n"
              L"--status overrides the NTSTATUS that CreateProcess sees on a "
              L"DENY match. Default 5 (STATUS_ACCESS_DENIED). 0 returns SUCCESS "
              L"so attackers checking the syscall return value won't notice. "
              L"Other useful small ints: 2=NAME_NOT_FOUND, 3=PATH_NOT_FOUND, "
              L"32=SHARING_VIOLATION, or pass a full NT hex like 0xC0000022. "
              L"Status is ignored for allow/log actions.\n"
              L"\n"
              L"WARNING: denying critical processes (csrss/wininit/services/lsass) "
              L"will brick the running session. Test on a VM.")
       .arg(wclap::Arg(L"pattern").positional().required()
                .help(L"Wildcard pattern against the image NT path"))
       .arg(wclap::Arg(L"action").positional().required()
                .help(L"allow | deny | log"))
       .arg(wclap::Arg(L"status").long_name(L"status").takes_value()
                .default_value(L"5")
                .help(L"NTSTATUS for DENY (decimal Win32 or 0x... NT hex). Default 5."));
    auto m = app.parse(argc, argv);
    std::wstring pattern = *m.value(L"pattern");
    int act = ParseProcAction(*m.value(L"action"));
    if (act < 0) {
        fwprintf(stderr, L"proc rule add: bad action '%ls' (use allow|deny|log)\n",
                 m.value(L"action")->c_str());
        return 1;
    }
    uint32_t status = ResolveStatusInput(*m.value(L"status"));
    bool isDeny = (act == 1);
    bool ghostDeny = isDeny && (status & 0x80000000u) == 0;
    DriverSession s;
    if (!OpenDriverOrHint(s)) return 1;
    auto id = s.procRuleAdd(pattern, (DriverSession::ProcRuleAction)act, status);
    if (!id) {
        fwprintf(stderr, L"proc rule add: failed (%lu)\n", ::GetLastError());
        return 1;
    }
    const wchar_t* statusName = WellKnownStatusName(status);
    if (*statusName) {
        wprintf(L"added rule %u: %ls -> %ls (status 0x%08X %ls)%ls\n",
                *id, pattern.c_str(), ProcActionName(act), status, statusName,
                ghostDeny ? L" [ghost-deny]" : L"");
    } else {
        wprintf(L"added rule %u: %ls -> %ls (status 0x%08X)%ls\n",
                *id, pattern.c_str(), ProcActionName(act), status,
                ghostDeny ? L" [ghost-deny]" : L"");
    }
    if (ghostDeny) {
        fwprintf(stderr,
            L"  note: ghost-deny mode active. CreateProcess() will return\n"
            L"  SUCCESS with valid hProcess/hThread; the process is\n"
            L"  terminated from the create-notify before its initial\n"
            L"  thread enters user mode, and its entry point is patched\n"
            L"  with a 2-byte infinite-loop shim as defense in depth.\n"
            L"  Caller's GetExitCodeProcess returns 0x%08X.\n", status);
    }
    return 0;
}

