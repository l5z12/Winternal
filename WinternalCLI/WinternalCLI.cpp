// `proc symbols` — DbgHelp-backed symbol resolver for system modules.
// Lets us locate functions (even non-exported ones) by name at install
// time, against whatever build is actually loaded on this machine. PDBs
// are auto-downloaded from msdl.microsoft.com and cached under
// %LOCALAPPDATA%\Winternal\Symbols\. Replaces hardcoded offsets, which
// would otherwise diverge between our build host and any other Windows
// build the user runs against.

// Common targets we know about. Used by `prefetch` to warm the cache
// and by `resolve --hook <id>` shortcuts.
struct KnownSymbol {
    const wchar_t* image;
    const char*    name;
    const wchar_t* purpose;
};
static const KnownSymbol kKnownSymbols[] = {
    { L"win32kfull.sys", "NtUserDestroyWindow",  L"win rule block-destroy hook" },
    { L"win32kfull.sys", "NtUserCreateWindowEx", L"future win rule block-create hook" },
    { L"win32kfull.sys", "xxxDestroyWindow",     L"internal worker (non-exported)" },
    { L"ntoskrnl.exe",   "NtLoadDriver",         L"drv rule deny hook" },
    // ntoskrnl's public PDB strips most `Psp*` private symbols, so don't
    // bother prefetching them -- they'll always miss. Add ntoskrnl entries
    // here only for symbols that show up in the public/global table.
};

static int CmdProcSymbolsPath(int argc, wchar_t** argv) {
    wclap::App app(L"winternal proc symbols path");
    app.about(L"Show the DbgHelp symbol search path. Driven by %_NT_SYMBOL_PATH% "
              L"if set, otherwise defaults to "
              L"srv*%LOCALAPPDATA%\\Winternal\\Symbols*https://msdl.microsoft.com/download/symbols.");
    app.parse(argc, argv);
    winternal::SymbolResolver r;
    if (!r.Initialize()) {
        fwprintf(stderr, L"symbols path: %ls\n", r.LastError().c_str());
        return 1;
    }
    wprintf(L"symbol path: %ls\n", r.SymbolPath().c_str());
    wprintf(L"local cache: %ls\n", r.CacheDirectory().c_str());
    return 0;
}

static int CmdProcSymbolsResolve(int argc, wchar_t** argv) {
    wclap::App app(L"winternal proc symbols resolve");
    app.about(L"Resolve a symbol in a system module to its RVA. Downloads "
              L"the matching PDB on first use (cached after). Returns 0 only "
              L"if found. Useful both as a diagnostic and as a manual way to "
              L"feed an offset into other tooling.")
       .arg(wclap::Arg(L"module").long_name(L"module").takes_value().required()
                .help(L"Module file name (e.g. win32kfull.sys) or full path"))
       .arg(wclap::Arg(L"name").long_name(L"name").takes_value().required()
                .help(L"Symbol name (e.g. NtUserDestroyWindow)"));
    auto m = app.parse(argc, argv);
    std::wstring module = *m.value(L"module");
    std::wstring nameW  = *m.value(L"name");
    std::string  name(nameW.begin(), nameW.end());

    winternal::SymbolResolver r;
    if (!r.Initialize()) {
        fwprintf(stderr, L"symbols resolve: init failed: %ls\n", r.LastError().c_str());
        return 1;
    }
    wprintf(L"resolving %ls!%hs ...\n", module.c_str(), name.c_str());
    uint64_t rva = r.Resolve(module, name);
    if (!rva) {
        fwprintf(stderr, L"  not found: %ls\n", r.LastError().c_str());
        return 1;
    }
    wprintf(L"  %ls!%hs = +0x%llX\n", module.c_str(), name.c_str(),
            (unsigned long long)rva);
    return 0;
}

static int CmdProcSymbolsPrefetch(int argc, wchar_t** argv) {
    wclap::App app(L"winternal proc symbols prefetch");
    app.about(L"Resolve a known set of system symbols ahead of time. Triggers "
              L"PDB download for win32kfull, ntoskrnl, etc. so future "
              L"hook-install commands run without a network stall.");
    app.parse(argc, argv);

    winternal::SymbolResolver r;
    if (!r.Initialize()) {
        fwprintf(stderr, L"symbols prefetch: init failed: %ls\n", r.LastError().c_str());
        return 1;
    }
    int ok = 0, fail = 0;
    for (const auto& k : kKnownSymbols) {
        wprintf(L"  %ls!%-32hs ... ", k.image, k.name);
        uint64_t rva = r.Resolve(k.image, k.name);
        if (rva) { wprintf(L"+0x%llX  (%ls)\n", (unsigned long long)rva, k.purpose); ++ok; }
        else     { wprintf(L"MISS  (%ls)\n", r.LastError().c_str()); ++fail; }
    }
    wprintf(L"prefetch: %d ok, %d miss\n", ok, fail);
    return fail ? 1 : 0;
}

