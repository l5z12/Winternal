// ---- proc protect: prohibit-exit-process rules ----
//
// Each rule is a wildcard pattern. The undocumented NtTerminateProcess
// prologue hook in the driver consults this list against the TARGET
// image at the moment a termination is attempted. A match returns
// STATUS_ACCESS_DENIED to the terminator (taskkill /F, SIGINT routers,
// debugger detach, etc.) without calling the original syscall.
// Self-termination is always allowed — otherwise the protected process
// itself couldn't exit cleanly and would livelock the system.
static int CmdProcProtectAdd(int argc, wchar_t** argv) {
    wclap::App app(L"winternal proc protect add");
    app.about(L"Add a termination-protect rule. Any NtTerminateProcess call "
              L"whose TARGET image matches will be refused with the per-rule "
              L"NTSTATUS — regardless of the caller's privilege (admin, "
              L"SYSTEM, anti-malware-light). Self-termination is always "
              L"permitted (otherwise the protected process couldn't exit). "
              L"Patterns are path-aware shell wildcards: `*` spans `\\`, "
              L"`?` matches one. Examples:\n"
              L"  *\\notepad.exe          -- block taskkill of notepad anywhere\n"
              L"  *\\winternal.exe        -- protect this CLI itself\n"
              L"  *\\System32\\lsass.exe  -- block lsass termination (be careful)\n"
              L"\n"
              L"--status overrides the NTSTATUS returned to the terminator. "
              L"Default 5 (STATUS_ACCESS_DENIED -- what taskkill expects). "
              L"0 returns SUCCESS, useful for fooling self-terminators or "
              L"detection scripts that gate on the syscall return. NOTE: "
              L"this is only honored when the NtTerminateProcess inline hook "
              L"is live. On HVCI/VBS systems the kernel blocks the CR0.WP\n"
              L"toggle the hook needs, so the rule falls back to the Ob handle-\n"
              L"strip path -- which can only ever yield STATUS_ACCESS_DENIED.\n"
              L"\n"
              L"NOTE: Different from `proc rule deny` (which blocks CREATE) "
              L"and from `protect <pid>` (handle-open layer, session-scoped).")
       .arg(wclap::Arg(L"pattern").positional().required()
                .help(L"Wildcard pattern against the target's image NT path"))
       .arg(wclap::Arg(L"status").long_name(L"status").takes_value()
                .default_value(L"5")
                .help(L"NTSTATUS to return on match (decimal Win32 or 0x... NT hex). Default 5."));
    auto m = app.parse(argc, argv);
    std::wstring pattern = *m.value(L"pattern");
    uint32_t status = ResolveStatusInput(*m.value(L"status"));
    DriverSession s;
    if (!OpenDriverOrHint(s)) return 1;
    uint32_t flags = 0;
    auto id = s.procProtectAdd(pattern, status, &flags);
    if (!id) {
        DWORD le = ::GetLastError();
        fwprintf(stderr, L"proc protect add: failed (%lu)\n", le);
        if (le == ERROR_ACCESS_DENIED || le == ERROR_NOT_READY) {
            fwprintf(stderr,
                L"  hint: neither enforcement path is live. The NtTerminate-\n"
                L"  Process inline hook (custom-status path) requires writable\n"
                L"  kernel code -- HVCI typically blocks the CR0.WP toggle. The\n"
                L"  HVCI-safe fallback is ObRegisterCallbacks; if THAT also\n"
                L"  failed, the driver is likely unsigned or the test-signing\n"
                L"  cert isn't trusted. Check `winternal driver status`.\n");
        }
        return 1;
    }
    const wchar_t* statusName = WellKnownStatusName(status);
    bool hookLive = (flags & WINTERNAL_PROC_PROTECT_FLAG_HOOK_LIVE) != 0;
    bool obLive   = (flags & WINTERNAL_PROC_PROTECT_FLAG_OB_LIVE)   != 0;
    const wchar_t* tag = hookLive ? L" [inline-hook]"
                       : obLive   ? L" [Ob-fallback]"
                                  : L"";
    if (*statusName) {
        wprintf(L"added protect rule %u: %ls (status 0x%08X %ls)%ls\n",
                *id, pattern.c_str(), status, statusName, tag);
    } else {
        wprintf(L"added protect rule %u: %ls (status 0x%08X)%ls\n",
                *id, pattern.c_str(), status, tag);
    }
    if (!hookLive && status != 0xC0000022u) {
        fwprintf(stderr,
            L"  note: enforcement is via the Ob handle-strip fallback (HVCI\n"
            L"  is blocking the NtTerminateProcess inline-hook write). That\n"
            L"  path can only refuse the open -- it cannot synthesize NTSTATUS\n"
            L"  values. Termination attempts on this rule will return\n"
            L"  STATUS_ACCESS_DENIED (0xC0000022) regardless of --status. To\n"
            L"  get a custom status: disable Memory Integrity in Settings >\n"
            L"  Windows Security > Device Security > Core Isolation, reboot,\n"
            L"  and re-add the rule.\n");
    }
    return 0;
}

